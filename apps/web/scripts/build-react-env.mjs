// Builds the ONE vendor script every Level 6 (React) strike loads inside its sandboxed iframe:
// window.React, window.ReactDOM (the react-dom/client API: createRoot, ...) and window.Babel
// (so the iframe can run real JSX with no build step, the well-known "React without a bundler"
// pattern — Babel scans the page for <script type="text/babel"> tags once DOMContentLoaded
// fires, and transforms + runs them in place).
//
// Why build this ourselves instead of using a CDN? Two reasons: staying fully offline (every
// other part of this app already works with zero network dependency, matching the project
// charter), and real version control — this exact bundle, from this exact repo's own react/
// react-dom, not whatever a CDN happens to be serving today.
//
// React 19 dropped the old UMD browser builds entirely, so there is no ready-made "just drop
// this script tag in" file to copy anymore: we bundle react + react-dom/client ourselves, with
// esbuild, into one small IIFE that sets those two globals, then glue Babel standalone's own
// already-browser-ready bundle onto the end of it.
//
// Run with: npm run build:react-env -w apps/web (also runs automatically before dev/build).
import { build } from "esbuild";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const publicDir = path.join(webRoot, "public");
const outFile = path.join(publicDir, "react-env.js");
// Real Node module resolution (walks up to the monorepo's hoisted root node_modules), instead
// of a hardcoded path that only works if @babel/standalone happens to live right next door.
const require = createRequire(import.meta.url);

const entry = `
  import * as React from "react";
  import * as ReactDOM from "react-dom/client";
  window.React = React;
  window.ReactDOM = ReactDOM;
`;

const result = await build({
  stdin: { contents: entry, resolveDir: webRoot, loader: "js" },
  bundle: true,
  format: "iife",
  platform: "browser",
  write: false,
  minify: true,
  logLevel: "warning",
});

const reactBundle = result.outputFiles[0].text;
const babelSource = readFileSync(require.resolve("@babel/standalone/babel.min.js"), "utf8");

mkdirSync(publicDir, { recursive: true });
writeFileSync(
  outFile,
  "// GENERATED by apps/web/scripts/build-react-env.mjs. Do not hand-edit; rebuild it instead.\n" +
    reactBundle +
    "\n" +
    babelSource +
    "\n",
);

console.log(
  `Wrote ${path.relative(webRoot, outFile)} (${(reactBundle.length + babelSource.length) / 1024 | 0} KB).`,
);
