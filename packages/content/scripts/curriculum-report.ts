// npm run curriculum:check
//
// Audits the Atlas and writes docs/curriculum/coverage-report.md: what is complete, what is an
// outline, what is missing, and the backlog. Exits with code 1 if there are any ERRORS, so CI fails.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allLessons } from "../index";
import {
  auditAtlas,
  domains,
  glossary,
  INTERVIEW_TARGET,
  topicCompleteness,
  topics,
} from "../atlas";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const findings = auditAtlas({
  domains,
  topics,
  glossary,
  strikeIds: allLessons.map((l) => l.id),
  requiredDomainCount: 16,
});
const errors = findings.filter((f) => f.level === "error");
const warnings = findings.filter((f) => f.level === "warning");

const complete = topics.filter((t) => t.stage === "complete");
const drafts = topics.filter((t) => t.stage === "draft");
const outlines = topics.filter((t) => t.stage === "outline");
const questionCount = topics.reduce((n, t) => n + t.interviewQuestions.length, 0);
const linkedStrikes = new Set(topics.flatMap((t) => t.strikeIds));

const lines: string[] = [];
const out = (s = "") => lines.push(s);

out("# Curriculum coverage report");
out();
out("Generated by `npm run curriculum:check` from `packages/content/atlas`. Do not edit by hand.");
out();
out("## Summary");
out();
out(`| Measure | Value |`);
out(`| --- | --- |`);
out(`| Domains | ${domains.length} of 16 required |`);
out(`| Modules | ${domains.reduce((n, d) => n + d.modules.length, 0)} |`);
out(`| Topics | ${topics.length} |`);
out(`| Complete topics (all 18 parts) | ${complete.length} |`);
out(`| Draft topics | ${drafts.length} |`);
out(`| Outline topics (goals only, lesson not written) | ${outlines.length} |`);
out(`| Interview questions with model answers | ${questionCount} (target: ${INTERVIEW_TARGET} per topic = ${topics.length * INTERVIEW_TARGET}) |`);
out(`| Glossary terms | ${glossary.length} |`);
out(`| Existing hands-on strikes linked from topics | ${linkedStrikes.size} of ${allLessons.length} |`);
out(`| Audit errors | ${errors.length} |`);
out(`| Audit warnings | ${warnings.length} |`);
out();
out("**Honest status:** the curriculum is NOT complete. Only the topics marked complete below have full lessons, projects, assessments and question banks. Every outline topic is in the backlog.");
out();
out("## By domain");
out();
out("| # | Domain | Topics | Complete | Outline | Interview Qs |");
out("| --- | --- | --- | --- | --- | --- |");
for (const d of domains) {
  const own = topics.filter((t) => t.domainId === d.id);
  out(`| ${d.number} | ${d.title} | ${own.length} | ${own.filter((t) => t.stage === "complete").length} | ${own.filter((t) => t.stage === "outline").length} | ${own.reduce((n, t) => n + t.interviewQuestions.length, 0)} |`);
}
out();
out("## Complete topics");
out();
out("| Topic | Parts passed | Interview bank | Exercises | Assessment Qs |");
out("| --- | --- | --- | --- | --- |");
for (const t of complete) {
  const c = topicCompleteness(t);
  const bank = t.interviewQuestions.length >= INTERVIEW_TARGET ? `${t.interviewQuestions.length}` : `${t.interviewQuestions.length} (below ${INTERVIEW_TARGET} target)`;
  out(`| ${t.title} (\`${t.id}\`) | ${c.passed}/${c.total} | ${bank} | ${t.exercises.length} | ${t.assessment?.questions.length ?? 0} |`);
}
out();
out("## Errors");
out();
if (errors.length === 0) out("None.");
for (const e of errors) out(`- \`${e.where}\`: ${e.message}`);
out();
out("## Warnings");
out();
if (warnings.length === 0) out("None.");
for (const w of warnings) out(`- \`${w.where}\`: ${w.message}`);
out();
out("## Backlog: outline topics still to write (in map order)");
out();
for (const d of domains) {
  const own = outlines.filter((t) => t.domainId === d.id);
  if (own.length === 0) continue;
  out(`### ${d.number}. ${d.title}`);
  out();
  for (const t of own) out(`- [ ] \`${t.id}\` ${t.title}${t.strikeIds.length ? ` (has ${t.strikeIds.length} linked strike${t.strikeIds.length > 1 ? "s" : ""})` : ""}`);
  out();
}

const reportDir = path.join(root, "docs", "curriculum");
mkdirSync(reportDir, { recursive: true });
writeFileSync(path.join(reportDir, "coverage-report.md"), lines.join("\n") + "\n");

console.log(`Atlas: ${domains.length} domains, ${topics.length} topics (${complete.length} complete, ${outlines.length} outline), ${questionCount} interview questions, ${glossary.length} glossary terms.`);
console.log(`Audit: ${errors.length} errors, ${warnings.length} warnings. Report: docs/curriculum/coverage-report.md`);
for (const e of errors) console.log(`ERROR ${e.where}: ${e.message}`);
if (errors.length > 0) process.exit(1);
